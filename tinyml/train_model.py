def _print_cm(cm):
    print("         " + "  ".join(f"{c:>12}" for c in CLASS_NAMES))
    for i, row in enumerate(cm):
        print(f"  {CLASS_NAMES[i]:>8}  " + "  ".join(f"{v:>12d}" for v in row))


def evaluate_sklearn(model, X_test, y_test, name="RF"):
    from sklearn.metrics import classification_report, confusion_matrix
    y_pred = model.predict(X_test)
    report = classification_report(y_test, y_pred, target_names=CLASS_NAMES, digits=3)
    cm = confusion_matrix(y_test, y_pred)
    print(f"\n[{name}] Test classification report:")
    print(report)
    print(f"[{name}] Test confusion matrix:")
    _print_cm(cm)
    return report, cm, y_pred


def evaluate_tflite(tflite_model_bytes, X_test_input, y_test, name="TFLite"):
    """Run TFLite interpreter on test set and report accuracy."""
    try:
        import tensorflow as tf
        interp = tf.lite.Interpreter(model_content=tflite_model_bytes)
    except Exception:
        _require("tflite_runtime", "pip install tflite-runtime")
        from tflite_runtime.interpreter import Interpreter
        import tempfile, os
        with tempfile.NamedTemporaryFile(delete=False, suffix=".tflite") as tmp:
            tmp.write(tflite_model_bytes)
            tmp_path = tmp.name
        interp = Interpreter(model_path=tmp_path)
        os.unlink(tmp_path)

    interp.allocate_tensors()
    inp_det = interp.get_input_details()[0]
    out_det = interp.get_output_details()[0]
    inp_scale, inp_zero = inp_det["quantization"]
    out_scale, out_zero = out_det["quantization"]

    preds = []
    for i in range(len(X_test_input)):
        x = X_test_input[i:i+1]
        if inp_det["dtype"] == np.int8:
            if inp_scale > 0:
                x_q = np.round(x / inp_scale + inp_zero).clip(-128, 127).astype(np.int8)
            else:
                x_q = x.astype(np.int8)
        else:
            x_q = x.astype(inp_det["dtype"])
        interp.set_tensor(inp_det["index"], x_q)
        interp.invoke()
        out = interp.get_tensor(out_det["index"])[0]
        if out_det["dtype"] == np.int8:
            out = (out.astype(np.float32) - out_zero) * out_scale
        preds.append(int(np.argmax(out)))

    from sklearn.metrics import classification_report, confusion_matrix
    y_pred = np.array(preds)
    report = classification_report(y_test, y_pred, target_names=CLASS_NAMES, digits=3)
    cm = confusion_matrix(y_test, y_pred)
    print(f"\n[{name}] Test classification report (int8 quantised):")
    print(report)
    print(f"[{name}] Confusion matrix:")
    _print_cm(cm)
    return report, cm, y_pred


def tflite_to_c_header(tflite_bytes, var_name, output_path):
    """Convert a .tflite flat-buffer to a C header with a uint8 array."""
    lines = [
        "// Auto-generated by train_model.py — DO NOT EDIT",
        "#pragma once",
        "#include <stdint.h>",
        f"// Model size: {len(tflite_bytes)} bytes",
        f"const unsigned int {var_name}_len = {len(tflite_bytes)};",
        f"alignas(8) const unsigned char {var_name}[] = {{",
    ]
    hex_vals = [f"0x{b:02x}" for b in tflite_bytes]
    for i in range(0, len(hex_vals), 16):
        lines.append("  " + ", ".join(hex_vals[i:i+16]) + ",")
    lines += ["};"]
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  C header written: {output_path}")


# ────────────────────────────────────────────────────────────
# Estimated arena size (heuristic, not measured on-device)
# ────────────────────────────────────────────────────────────

def estimate_arena_bytes_mlp():
    # MLP: Input(16) -> Dense(32) -> Dense(16) -> Dense(4)
    # Activations: 32 + 16 + 4 = 52 floats = 208 bytes (float32 or int8)
    # TFLite Micro overhead: ~2-4 KB typical for a model this size
    return 4 * 1024   # conservative estimate 4 KB

def estimate_arena_bytes_cnn():
    # CNN: (125,6) -> Conv1D(8,k=7,s=2)->(63,8) -> Conv1D(16,k=5,s=2)->(32,16)
    #   -> GAP -> Dense(16) -> Dense(4)
    # Largest activation tensor: 63*8=504 floats (int8: 504 bytes) plus Conv scratch
    # TFLite Micro overhead ~6-10 KB
    return 12 * 1024  # conservative estimate 12 KB


