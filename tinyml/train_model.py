def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset",  default="dataset/")
    parser.add_argument("--output",   default="models/")
    parser.add_argument("--skip_cnn", action="store_true", help="Skip CNN training (saves time)")
    parser.add_argument("--skip_mlp", action="store_true", help="Skip MLP training")
    args = parser.parse_args()

    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)

    print("Loading dataset and extracting features...")
    splits = load_features(args.dataset)
    Xf_tr, y_tr, X_tr_raw = splits["train"]
    Xf_val, y_val, X_val_raw = splits["val"]
    Xf_te, y_te, X_te_raw  = splits["test"]

    # Feature scaling (for RF and MLP)
    fmin, fmax = load_scaler_stats(Xf_tr)
    Xs_tr  = scale_features(Xf_tr, fmin, fmax)
    Xs_val = scale_features(Xf_val, fmin, fmax)
    Xs_te  = scale_features(Xf_te, fmin, fmax)
    np.save(out / "scaler_min.npy", fmin)
    np.save(out / "scaler_max.npy", fmax)

    results = {}

    # ── (a) Random Forest ──────────────────────────────────
    rf, rf_val_report, _ = train_random_forest(Xs_tr, y_tr, Xs_val, y_val)
    rf_report, rf_cm, rf_preds = evaluate_sklearn(rf, Xs_te, y_te, "RF")

    # Save joblib model for robustness_test.py and validate_real.py
    import joblib
    joblib.dump(rf, out / "model_rf.joblib")
    print(f"[RF] Saved scikit-learn model -> {out / 'model_rf.joblib'}")

    # Estimate model size: encode trees to C header and check file size
    rf_c_path = str(out / "model_rf.h")
    rf_size   = rf_to_c_code(rf, fmin, fmax, rf_c_path)
    # RF runs entirely on float features — no arena needed beyond feature buffer (16*4=64 bytes)
    rf_arena  = 256   # ~256 bytes for vote counters + stack

    from sklearn.metrics import accuracy_score
    rf_acc = accuracy_score(y_te, rf_preds)
    results["RF"] = {
        "test_acc": float(rf_acc),
        "model_bytes": rf_size,
        "arena_bytes": rf_arena,
        "report": rf_report,
    }

    # ── (b) MLP ────────────────────────────────────────────
    if not args.skip_mlp:
        mlp_model, _ = train_mlp(Xs_tr, y_tr.astype(np.int32),
                                  Xs_val, y_val.astype(np.int32))
        mlp_tflite_path = str(out / "model_mlp.tflite")
        mlp_tflite, mlp_size = mlp_to_tflite_int8(mlp_model, Xs_tr, mlp_tflite_path)

        # TFLite int8 evaluation
        mlp_report, mlp_cm, mlp_preds = evaluate_tflite(mlp_tflite, Xs_te, y_te, "MLP-int8")
        mlp_acc = accuracy_score(y_te, mlp_preds)

        # Write C header for firmware
        tflite_to_c_header(mlp_tflite, "g_mlp_model", str(out / "model_mlp_data.h"))

        results["MLP-int8"] = {
            "test_acc": float(mlp_acc),
            "model_bytes": mlp_size,
            "arena_bytes": estimate_arena_bytes_mlp(),
            "report": mlp_report,
        }
    else:
        print("[MLP] Skipped.")

