# Model (a): Random Forest → C code
# ────────────────────────────────────────────────────────────

def train_random_forest(X_tr, y_tr, X_val, y_val):
    sklearn = _require("sklearn", "pip install scikit-learn")
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.metrics import classification_report, confusion_matrix

    print("\n[RF] Training Random Forest...")
    t0 = time.time()
    rf = RandomForestClassifier(
        n_estimators=20,
        max_depth=8,
        min_samples_leaf=4,
        random_state=SEED,
        n_jobs=-1,
    )
    rf.fit(X_tr, y_tr)
    t1 = time.time()
    print(f"  Train time: {t1-t0:.2f}s")

    y_pred_val = rf.predict(X_val)
    report = classification_report(y_val, y_pred_val, target_names=CLASS_NAMES, digits=3)
    cm = confusion_matrix(y_val, y_pred_val)
    print("[RF] Validation report:")
    print(report)
    print("[RF] Confusion matrix (val):")
    _print_cm(cm)

    return rf, report, cm


def rf_to_c_code(rf, fmin, fmax, output_path):
    """
    Export a sklearn RandomForestClassifier to a self-contained C header.
    Uses a recursive descent evaluator (no malloc, pure stack).
    Estimated flash: ~1–3 KB per tree * n_estimators.
    """
    from sklearn.tree import DecisionTreeClassifier

    lines = []
    lines += [
        "// Auto-generated by train_model.py — DO NOT EDIT",
        "// Random Forest classifier for cargo shock/handling (4 classes)",
        "#pragma once",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        f"#define RF_NUM_FEATURES  {rf.n_features_in_}",
        f"#define RF_NUM_CLASSES   {rf.n_classes_}",
        f"#define RF_NUM_TREES     {len(rf.estimators_)}",
        "",
        "// Feature scaling constants (train set min/max -> [-1, 1])",
        "static const float RF_FEAT_MIN[RF_NUM_FEATURES] = {",
        "  " + ", ".join(f"{v:.6f}f" for v in fmin),
        "};",
        "static const float RF_FEAT_MAX[RF_NUM_FEATURES] = {",
        "  " + ", ".join(f"{v:.6f}f" for v in fmax),
        "};",
        "",
    ]

    # Encode each tree as threshold/feature/left/right/value arrays
    all_tree_structs = []
    for ti, estimator in enumerate(rf.estimators_):
        t = estimator.tree_
        n = t.node_count
        lines += [f"// Tree {ti}: {n} nodes"]
        lines += [f"static const int8_t  RF_T{ti}_FEAT[{n}]  = {{",
                  "  " + ", ".join(str(int(v)) for v in t.feature) + "};"]
        lines += [f"static const float   RF_T{ti}_THR[{n}]   = {{",
                  "  " + ", ".join(f"{v:.6f}f" for v in t.threshold) + "};"]
        lines += [f"static const int16_t RF_T{ti}_LEFT[{n}]  = {{",
                  "  " + ", ".join(str(int(v)) for v in t.children_left) + "};"]
        lines += [f"static const int16_t RF_T{ti}_RIGHT[{n}] = {{",
                  "  " + ", ".join(str(int(v)) for v in t.children_right) + "};"]
        # Majority class per leaf: argmax of value[node, 0, :]
        leaf_class = np.argmax(t.value[:, 0, :], axis=1).astype(np.int8)
        lines += [f"static const int8_t  RF_T{ti}_CLASS[{n}] = {{",
                  "  " + ", ".join(str(v) for v in leaf_class) + "};"]
        lines += [""]
        all_tree_structs.append(ti)

    # Inference function
    lines += [
        "static inline int8_t _rf_predict_tree(",
        "    const int8_t *feat, const float *thr,",
        "    const int16_t *left, const int16_t *right,",
        "    const int8_t *cls_arr, const float *x_scaled)",
        "{",
        "  int16_t node = 0;",
        "  while (feat[node] >= 0) {",
        "    if (x_scaled[feat[node]] <= thr[node])",
        "      node = left[node];",
        "    else",
        "      node = right[node];",
        "  }",
        "  return cls_arr[node];",
        "}",
        "",
        "// Scale one feature vector in-place (fills x_out from x_raw)",
        "static inline void rf_scale_features(const float *x_raw, float *x_out) {",
        "  for (int i = 0; i < RF_NUM_FEATURES; i++) {",
        "    float denom = RF_FEAT_MAX[i] - RF_FEAT_MIN[i];",
        "    if (denom < 1e-6f) denom = 1.0f;",
        "    x_out[i] = 2.0f * (x_raw[i] - RF_FEAT_MIN[i]) / denom - 1.0f;",
        "  }",
        "}",
        "",
        "// Main inference: x_raw = 16 unscaled features, returns class 0-3",
        "// votes[] is optional output (NULL to skip); pass float[4]",
        "static inline int8_t rf_predict(const float *x_raw, float *votes) {",
        "  float x_scaled[RF_NUM_FEATURES];",
        "  rf_scale_features(x_raw, x_scaled);",
        "  int counts[RF_NUM_CLASSES] = {0};",
        "",
    ]
    for ti in all_tree_structs:
        lines += [
            f"  counts[_rf_predict_tree(RF_T{ti}_FEAT, RF_T{ti}_THR,",
            f"    RF_T{ti}_LEFT, RF_T{ti}_RIGHT, RF_T{ti}_CLASS, x_scaled)]++;",
        ]
    lines += [
        "  if (votes) {",
        "    for (int i=0;i<RF_NUM_CLASSES;i++)",
        f"      votes[i]=(float)counts[i]/{len(all_tree_structs)}.0f;",
        "  }",
        "  int best=0; for(int i=1;i<RF_NUM_CLASSES;i++) if(counts[i]>counts[best]) best=i;",
        "  return (int8_t)best;",
        "}",
    ]

    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    size = os.path.getsize(output_path)
    print(f"  [RF] C header written: {output_path} ({size} bytes)")
    return size


# ────────────────────────────────────────────────────────────
# Model (b): Small MLP (feature-based) → TFLite int8
# ────────────────────────────────────────────────────────────

def train_mlp(X_tr, y_tr, X_val, y_val):
    """Train a tiny 2-layer MLP on the 16 features."""
    tf = _require("tensorflow", "pip install tensorflow>=2.13")
    from tensorflow import keras
    import tensorflow as tf2

    tf2.random.set_seed(SEED)
    np.random.seed(SEED)

    model = keras.Sequential([
        keras.layers.Input(shape=(NUM_FEATURES,)),
        keras.layers.Dense(32, activation="relu"),
        keras.layers.Dense(16, activation="relu"),
        keras.layers.Dense(4, activation="softmax"),
    ], name="mlp_cargo")

    model.compile(
        optimizer=keras.optimizers.Adam(1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )
    model.summary()

    cb = [
        keras.callbacks.EarlyStopping(patience=10, restore_best_weights=True),
        keras.callbacks.ReduceLROnPlateau(factor=0.5, patience=5),
    ]
    history = model.fit(
        X_tr, y_tr,
        validation_data=(X_val, y_val),
        epochs=100, batch_size=256,
        callbacks=cb, verbose=1,
    )
    return model, history


def mlp_to_tflite_int8(model, X_repr, output_path):
    """Quantize MLP to int8 TFLite and save."""
    import tensorflow as tf

    def representative_dataset():
        idx = np.random.default_rng(0).integers(0, len(X_repr), 200)
        for i in idx:
            yield [X_repr[i:i+1]]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type  = tf.int8
    converter.inference_output_type = tf.int8

    tflite_model = converter.convert()
    with open(output_path, "wb") as f:
        f.write(tflite_model)
    size = len(tflite_model)
    print(f"  [MLP] TFLite int8 model: {output_path} ({size} bytes)")
    return tflite_model, size


# ────────────────────────────────────────────────────────────
# Model (c): 1D-CNN on raw windows → TFLite int8
# ────────────────────────────────────────────────────────────

def train_cnn(X_tr_raw, y_tr, X_val_raw, y_val):
    """
    Small 1D-CNN on raw (125, 6) int16 windows, cast to float32 and scaled.
    Architecture designed to fit within 24 KB arena.
    """
    tf = _require("tensorflow", "pip install tensorflow>=2.13")
    from tensorflow import keras
    import tensorflow as tf2

    tf2.random.set_seed(SEED)

    # Normalise raw to float32 in [-1, 1] range
    def norm(X):
        X = X.astype(np.float32)
        X[:, :, :3] /= 32768.0   # accel
        X[:, :, 3:] /= 32768.0   # gyro (same range)
        return X

    X_tr  = norm(X_tr_raw)
    X_val_n = norm(X_val_raw)

    model = keras.Sequential([
        keras.layers.Input(shape=(WINDOW_SAMPLES, 6)),
        keras.layers.Conv1D(8, kernel_size=7, strides=2, activation="relu", padding="same"),
        keras.layers.Conv1D(16, kernel_size=5, strides=2, activation="relu", padding="same"),
        keras.layers.GlobalAveragePooling1D(),
        keras.layers.Dense(16, activation="relu"),
        keras.layers.Dense(4, activation="softmax"),
    ], name="cnn_cargo")

    model.compile(
        optimizer=keras.optimizers.Adam(1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )
    model.summary()

    cb = [
        keras.callbacks.EarlyStopping(patience=10, restore_best_weights=True),
    ]
    history = model.fit(
        X_tr, y_tr,
        validation_data=(X_val_n, y_val),
        epochs=80, batch_size=256,
        callbacks=cb, verbose=1,
    )
    return model, history, norm


