# Lazy imports with helpful error messages
# ────────────────────────────────────────────────────────────
def _require(pkg, install_hint):
    try:
        return __import__(pkg)
    except ImportError:
        print(f"[ERROR] Missing '{pkg}'. Install: {install_hint}")
        sys.exit(1)

SEED = 42
CLASS_NAMES = ["normal", "shock", "drop", "rough_handling"]
NUM_FEATURES = 16
WINDOW_SAMPLES = 125

# Hardware budgets
MAX_ARENA_BYTES = 24 * 1024   # 24 KB
MAX_MODEL_BYTES = 60 * 1024   # 60 KB

# ────────────────────────────────────────────────────────────
# Feature loading
# ────────────────────────────────────────────────────────────

def load_features(dataset_dir):
    """Load raw windows and extract features for train/val/test."""
    from features import extract_features_batch

    d = Path(dataset_dir)
    result = {}
    for split in ["train", "val", "test"]:
        X = np.load(d / f"X_{split}.npy")   # (N, 125, 6) int16
        y = np.load(d / f"y_{split}.npy")   # (N,) int8
        print(f"  Extracting features: {split} ({len(y)} windows)...")
        Xf = extract_features_batch(X)       # (N, 16) float32
        result[split] = (Xf, y.astype(np.int64), X)
    return result


def load_scaler_stats(X_train_feat):
    """Compute min/max per feature on training set (for int8 quantisation)."""
    fmin = X_train_feat.min(axis=0)
    fmax = X_train_feat.max(axis=0)
    return fmin, fmax


def scale_features(X, fmin, fmax):
    """Scale features to [-1, 1] range using train set statistics."""
    denom = fmax - fmin
    denom[denom < 1e-6] = 1.0
    return 2.0 * (X - fmin) / denom - 1.0


