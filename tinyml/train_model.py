#!/usr/bin/env python3
"""
train_model.py — Phase 3: Train and compare classifiers for shock/handling.

Trains three candidates:
  (a) Decision Tree / Random Forest  -> exported to plain C array
  (b) Small MLP on features          -> TFLite int8
  (c) 1D-CNN on raw windows          -> TFLite int8

Evaluates on the held-out test split and selects the best model within
the ESP32 hardware budget:
  - Tensor arena: <= 24 KB
  - Model flash:  <= 60 KB
  - Classes:      0=normal, 1=shock, 2=drop, 3=rough_handling

Usage:
  python train_model.py --dataset dataset/ --output models/
  python train_model.py --dataset dataset/ --output models/ --skip_cnn

Pinned random seeds everywhere. All numbers reported are on the synthetic
test split only; NOT real-world accuracy.
"""

