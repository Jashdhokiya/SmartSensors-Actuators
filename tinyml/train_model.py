def select_and_report(results, output_dir):
    """
    Print a comparison table. Select winner based on:
    1. Must fit within MAX_MODEL_BYTES and MAX_ARENA_BYTES
    2. Highest test accuracy (macro F1)
    3. Tie-break: smallest model size
    """
    print("\n" + "="*70)
    print("MODEL COMPARISON (all on synthetic test set only)")
    print("="*70)
    print(f"  {'Model':12s}  {'Test Acc':>10}  {'Model KB':>10}  {'Arena KB':>10}  {'Fits?':>6}")
    print("-"*70)

    candidates = []
    for name, r in results.items():
        acc  = r.get("test_acc", 0.0)
        msz  = r.get("model_bytes", 0) / 1024
        asz  = r.get("arena_bytes", 0) / 1024
        fits = r.get("model_bytes", 0) <= MAX_MODEL_BYTES and \
               r.get("arena_bytes", 0) <= MAX_ARENA_BYTES
        print(f"  {name:12s}  {acc:>10.3f}  {msz:>10.1f}  {asz:>10.1f}  {'YES' if fits else 'NO':>6}")
        if fits:
            candidates.append((acc, -r.get("model_bytes", 0), name))

    if candidates:
        candidates.sort(reverse=True)
        winner = candidates[0][2]
        print(f"\n  >>> SELECTED: {winner} <<<")
        print("  (Best accuracy within ESP32 flash+arena budget)")
    else:
        print("\n  [!] No model fits within budget — check model sizes above.")
        winner = None

    print("="*70)
    report_path = Path(output_dir) / "comparison_report.json"
    with open(report_path, "w") as f:
        json.dump({"results": {k: {kk: vv for kk, vv in v.items()
                                    if isinstance(vv, (int, float, str, list))}
                               for k, v in results.items()},
                   "selected": winner}, f, indent=2)
    print(f"  Report saved: {report_path}")
    return winner


# ────────────────────────────────────────────────────────────
# Main
